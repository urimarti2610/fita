"""Builds the LibreOffice extension: dist/<id>-libreoffice-<version>.oxt.

The name, website and identifiers come from packages/core/src/brand.ts and the
menu/description text from wordanchor/i18n.py, so nothing is duplicated by hand.
Only the Python standard library is used.

Usage: python3 scripts/build.py
"""

from __future__ import annotations

import json
import os
import re
import shutil
import sys
import zipfile
from urllib.parse import urlparse
from xml.sax.saxutils import escape, quoteattr

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(os.path.dirname(ROOT))
SOURCE = os.path.join(ROOT, "extension")
DIST = os.path.join(ROOT, "dist")
# Fixed timestamp: the same sources always give the same .oxt.
DATE = (2026, 1, 1, 0, 0, 0)
MIN_LIBREOFFICE = "7.0"

sys.path.insert(0, os.path.join(SOURCE, "pythonpath"))
from wordanchor.i18n import MESSAGES  # noqa: E402


def read_brand() -> dict:
    with open(os.path.join(REPO, "packages", "core", "src", "brand.ts"), encoding="utf-8") as f:
        source = f.read()

    def field(name):
        match = re.search(rf'\b{name}:\s*"([^"]+)"', source)
        if not match:
            raise SystemExit(f"brand.ts: missing {name}")
        return match.group(1)

    name, brand_id, website = field("name"), field("id"), field("website")
    reverse_host = ".".join(reversed(urlparse(website).hostname.split(".")))
    return {
        "NAME": name,
        "ID": brand_id,
        "WEBSITE": website,
        "EXTENSION_ID": f"{reverse_host}.{brand_id}.writer",
        "IMPLEMENTATION": f"{reverse_host}.{brand_id}.WriterEmphasis",
        "STYLE_NAME": f"{name} emphasis",
    }


def read_version() -> str:
    with open(os.path.join(ROOT, "package.json"), encoding="utf-8") as f:
        return json.load(f)["version"]


def brand_module(brand: dict) -> str:
    lines = ['"""Generated by scripts/build.py from packages/core/src/brand.ts."""', ""]
    lines += [f"{key} = {json.dumps(value, ensure_ascii=False)}" for key, value in brand.items()]
    return "\n".join(lines) + "\n"


MENU = [
    ("document", "menuDocument"),
    ("selection", "menuSelection"),
    ("remove", "menuRemove"),
    None,
    ("style:bold", "menuBold"),
    ("style:color", "menuColor"),
    ("style:underline", "menuUnderline"),
    None,
    ("strength:lighter", "menuLighter"),
    ("strength:medium", "menuMedium"),
    ("strength:stronger", "menuStronger"),
]


def prop(name: str, values: str) -> str:
    return f'<prop oor:name="{name}" oor:type="xs:string">{values}</prop>'


def localized(key: str) -> str:
    # The value without xml:lang is the fallback for languages not listed.
    out = f"<value>{escape(MESSAGES['en'][key])}</value>"
    for lang, messages in MESSAGES.items():
        out += f'<value xml:lang="{lang}">{escape(messages[key])}</value>'
    return out


def addons_xcu(brand: dict) -> str:
    context = prop("Context", "<value>com.sun.star.text.TextDocument</value>")
    target = prop("Target", "<value>_self</value>")
    items = []
    for index, item in enumerate(MENU):
        url = "private:separator" if item is None else f"service:{brand['IMPLEMENTATION']}?{item[0]}"
        title = "" if item is None else prop("Title", localized(item[1]))
        items.append(
            f'<node oor:name="m{index:02d}" oor:op="replace">'
            f"{prop('URL', f'<value>{escape(url)}</value>')}{title}{target}{context}</node>"
        )
    submenu = "\n          ".join(items)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<oor:component-data xmlns:oor="http://openoffice.org/2001/registry" xmlns:xs="http://www.w3.org/2001/XMLSchema" oor:name="Addons" oor:package="org.openoffice.Office">
  <node oor:name="AddonUI">
    <node oor:name="OfficeMenuBar">
      <node oor:name={quoteattr(brand["EXTENSION_ID"])} oor:op="replace">
        {prop("Title", f"<value>{escape(brand['NAME'])}</value>")}
        {target}
        {context}
        <node oor:name="Submenu">
          {submenu}
        </node>
      </node>
    </node>
  </node>
</oor:component-data>
"""


def description_xml(brand: dict, version: str) -> str:
    names = "".join(
        f"<name lang={quoteattr(lang)}>{escape(m['displayName'].format(name=brand['NAME']))}</name>"
        for lang, m in MESSAGES.items()
    )
    descriptions = "".join(
        f'<src xlink:href="description/description-{lang}.txt" lang={quoteattr(lang)}/>'
        for lang in MESSAGES
    )
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<description xmlns="http://openoffice.org/extensions/description/2006"
             xmlns:xlink="http://www.w3.org/1999/xlink"
             xmlns:d="http://openoffice.org/extensions/description/2006"
             xmlns:l="http://libreoffice.org/extensions/description/2011">
  <identifier value={quoteattr(brand["EXTENSION_ID"])}/>
  <version value={quoteattr(version)}/>
  <platform value="all"/>
  <dependencies>
    <l:LibreOffice-minimal-version value="{MIN_LIBREOFFICE}" d:name="LibreOffice {MIN_LIBREOFFICE}"/>
  </dependencies>
  <publisher><name xlink:href={quoteattr(brand["WEBSITE"])} lang="en">{escape(brand["NAME"])}</name></publisher>
  <display-name>{names}</display-name>
  <extension-description>{descriptions}</extension-description>
  <icon><default xlink:href="icon.png"/></icon>
</description>
"""


MANIFEST = """<?xml version="1.0" encoding="UTF-8"?>
<manifest:manifest xmlns:manifest="http://openoffice.org/2001/manifest">
  <manifest:file-entry manifest:full-path="component.py" manifest:media-type="application/vnd.sun.star.uno-component;type=Python"/>
  <manifest:file-entry manifest:full-path="Addons.xcu" manifest:media-type="application/vnd.sun.star.configuration-data"/>
</manifest:manifest>
"""


def collect(brand: dict, version: str) -> dict:
    """Maps each path inside the .oxt to its bytes."""
    files = {}
    for folder, dirs, names in os.walk(SOURCE):
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        for name in names:
            if name.endswith(".pyc"):
                continue
            path = os.path.join(folder, name)
            with open(path, "rb") as f:
                files[os.path.relpath(path, SOURCE).replace(os.sep, "/")] = f.read()
    files["pythonpath/wordanchor/brand.py"] = brand_module(brand).encode()
    files["Addons.xcu"] = addons_xcu(brand).encode()
    files["description.xml"] = description_xml(brand, version).encode()
    files["META-INF/manifest.xml"] = MANIFEST.encode()
    for lang, messages in MESSAGES.items():
        files[f"description/description-{lang}.txt"] = (messages["description"] + "\n").encode()
    for name in ("LICENSE", "NOTICE"):
        with open(os.path.join(REPO, name), "rb") as f:
            files[name] = f.read()
    with open(os.path.join(REPO, "apps", "extension", "static", "icons", "icon-128.png"), "rb") as f:
        files["icon.png"] = f.read()
    return files


def build() -> str:
    brand = read_brand()
    version = read_version()
    shutil.rmtree(DIST, ignore_errors=True)
    os.makedirs(DIST)
    target = os.path.join(DIST, f"{brand['ID']}-libreoffice-{version}.oxt")
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
        for path, data in sorted(collect(brand, version).items()):
            archive.writestr(zipfile.ZipInfo(path, DATE), data, zipfile.ZIP_DEFLATED)
    return target


if __name__ == "__main__":
    print(os.path.relpath(build(), ROOT))
