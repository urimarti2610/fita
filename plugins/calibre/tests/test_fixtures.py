"""The Python port must match the TypeScript core exactly on the shared fixtures
(plugins/fixtures/emphasis.json, generated by packages/core/test/ports.test.ts)."""

import json
import os
import sys
import unittest

HERE = os.path.dirname(__file__)
sys.path.insert(0, os.path.join(HERE, "..", "plugin"))

from engine.emphasis import emphasize, resolve_options  # noqa: E402

FIXTURES = os.path.join(HERE, "..", "..", "fixtures", "emphasis.json")
NAMES = {"strength": "strength", "minWordLength": "min_word_length", "every": "every", "skipNumbers": "skip_numbers"}


class SharedFixtures(unittest.TestCase):
    def test_matches_core(self):
        with open(FIXTURES, encoding="utf-8") as f:
            cases = json.load(f)
        self.assertGreater(len(cases), 100)
        for case in cases:
            options = resolve_options(**{NAMES[k]: v for k, v in case["options"].items()})
            spans = emphasize(case["text"], options)
            got = "".join(f"[{s.text}]" if s.emphasis else s.text for s in spans)
            self.assertEqual(got, case["expected"], case["text"])


if __name__ == "__main__":
    unittest.main()
