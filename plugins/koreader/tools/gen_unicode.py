#!/usr/bin/env python3
"""Generates fita.koplugin/fita_unicode.lua: the Unicode data the Lua port needs.

Lua has no Unicode tables, so the character classes are exported from the
Python engine of the calibre plugin (plugins/calibre/plugin/engine/emphasis.py),
which keeps both ports classifying characters identically.

    python3 plugins/koreader/tools/gen_unicode.py
"""

import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "calibre", "plugin"))

from engine import emphasis  # noqa: E402

TARGET = os.path.join(HERE, "..", "fita.koplugin", "fita_unicode.lua")

# Bit layout of each value (see fita_unicode.lua's header).
EXTEND, PICTOGRAPHIC, LETTER, NUMBER, SPACE = 16, 32, 64, 128, 256
#: JavaScript's \s besides the Zs category.
JS_SPACES = {0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x2028, 0x2029, 0xFEFF}


def value(cp):
    if 0xD800 <= cp <= 0xDFFF:
        return 0
    ch = chr(cp)
    cat = unicodedata.category(ch)
    v = emphasis._word_class(ch)
    if cat in ("Mn", "Mc", "Me") or cp in (0x200C, 0x200D) or 0x1F3FB <= cp <= 0x1F3FF:
        v |= EXTEND
    if cat == "So":
        v |= PICTOGRAPHIC
    if cat[0] == "L":
        v |= LETTER
    if cat[0] == "N":
        v |= NUMBER
    if cat == "Zs" or cp in JS_SPACES:
        v |= SPACE
    return v


def main():
    starts, values = [], []
    previous = None
    for cp in range(0x110000):
        v = value(cp)
        if v != previous:
            starts.append(cp)
            values.append(v)
            previous = v
    names = (
        "OTHER LETTER HEBREW NUMERIC KATAKANA HANGUL EXTEND MID_LETTER MID_NUM_LET MID_NUM "
        "SINGLE_QUOTE DOUBLE_QUOTE EXTEND_NUM_LET"
    ).split()
    classes = {name: getattr(emphasis, f"_{name}") for name in names}
    assert max(classes.values()) < 16
    lines = [
        "-- Generated by tools/gen_unicode.py from Python's unicodedata "
        f"{unicodedata.unidata_version}. Do not edit.",
        "-- Each run of code points starting at starts[i] has values[i]:",
        "-- bits 0-3 word class, 16 grapheme extend, 32 symbol (So), 64 letter (L),",
        "-- 128 number (N), 256 space (JavaScript \\s).",
        "return {",
        "  classes = {",
    ]
    for name, number in sorted(classes.items(), key=lambda kv: kv[1]):
        lines.append(f"    {name} = {number},")
    lines.append("  },")
    for name, data in (("starts", starts), ("values", values)):
        lines.append(f"  {name} = {{")
        for i in range(0, len(data), 16):
            lines.append("    " + ",".join(str(x) for x in data[i : i + 16]) + ",")
        lines.append("  },")
    lines.append("}")
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(TARGET, len(starts), "runs")


if __name__ == "__main__":
    main()
